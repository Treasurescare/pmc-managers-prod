import { useState } from "react";

export default function PackageCard({ pkg, onDragStart, fmt }) {
  const [open, setOpen] = useState(false);

  const handlePrint = () => {
    const win = window.open("", "_blank", "width=900,height=1000");
    if (!win) return;
    const escape = (s) => String(s ?? "—")
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
    const rows = [
      ["Package reference", pkg.package_ref],
      ["Title", pkg.title],
      ["Category", pkg.category],
      ["Sub-category", pkg.sub_category],
      ["Status", pkg.status],
      ["Phase", pkg.phase],
      ["Estimated value", fmt(pkg.value, pkg.currency)],
      ["Currency", pkg.currency],
      ["Float target date", pkg.float_target_date ? pkg.float_target_date.slice(0, 10) : "—"],
      ["Owner", pkg.owner_email || pkg.created_by],
      ["Created at", pkg.created_at ? new Date(pkg.created_at).toLocaleString() : "—"],
      ["Notice reference", pkg.notice_ref || "Not yet floated"],
      ["Location", pkg.location],
      ["Delivery country", pkg.delivery_country],
      ["Duration", pkg.duration_months ? `${pkg.duration_months} months` : "—"],
    ];
    win.document.write(`<!doctype html><html><head><title>${escape(pkg.package_ref)} — ${escape(pkg.title)}</title>
      <style>
        body { font: 12px/1.5 -apple-system, Segoe UI, sans-serif; color:#14261F; padding: 40px 60px; max-width: 800px; margin: 0 auto; }
        .head { border-bottom: 2px solid #0F3B2E; padding-bottom: 14px; margin-bottom: 24px; }
        .head .ref { font: 10px/1 ui-monospace, monospace; letter-spacing: .2em; color:#7A5F1E; text-transform: uppercase; }
        h1 { font: 500 26px/1.15 Georgia, serif; color:#0F3B2E; margin: 6px 0 4px; }
        h2 { font: 600 11px/1 -apple-system, sans-serif; color:#7A5F1E; letter-spacing: .18em; text-transform: uppercase; margin: 22px 0 8px; }
        table { width:100%; border-collapse: collapse; }
        th, td { padding: 6px 0; border-bottom: 1px solid #E2DBC7; text-align: left; vertical-align: top; }
        th { width: 200px; color:#4F5C55; font-weight: 500; }
        td { color: #14261F; }
        .desc { white-space: pre-wrap; background:#FBF9F3; border: 1px solid #E2DBC7; padding: 14px 16px; }
        .foot { margin-top: 30px; padding-top: 12px; border-top: 1px solid #E2DBC7; font: 10px/1.4 ui-monospace, monospace; color:#4F5C55; }
        @media print { body { padding: 20px 30px; } }
      </style></head><body>
      <div class="head">
        <div class="ref">Work Package · ${escape(pkg.package_ref)}</div>
        <h1>${escape(pkg.title)}</h1>
        <div style="color:#4F5C55">${escape(pkg.category || "General")} · ${escape(pkg.delivery_country || "—")}</div>
      </div>
      <h2>Package details</h2>
      <table>${rows.filter(([, v]) => v !== null && v !== undefined && v !== "").map(([k, v]) => `<tr><th>${escape(k)}</th><td>${escape(v)}</td></tr>`).join("")}</table>
      ${pkg.description ? `<h2>Scope / description</h2><div class="desc">${escape(pkg.description)}</div>` : ""}
      ${Array.isArray(pkg.milestones) && pkg.milestones.length ? `<h2>Milestones</h2><table>${pkg.milestones.map((m) => `<tr><th>${escape(m.due_date ? m.due_date.slice(0, 10) : "—")}</th><td>${escape(m.title || m.description || "Milestone")}</td></tr>`).join("")}</table>` : ""}
      ${Array.isArray(pkg.deliverables) && pkg.deliverables.length ? `<h2>Deliverables</h2><ul>${pkg.deliverables.map((d) => `<li>${escape(d.title || d)}</li>`).join("")}</ul>` : ""}
      <div class="foot">Generated by PMC Managers · Global Tender Grid · ${new Date().toISOString()}</div>
      <script>window.onload = function(){ window.print(); };</script>
      </body></html>`);
    win.document.close();
  };

  const handleDownload = () => {
    const rows = [
      ["Package reference", pkg.package_ref],
      ["Title", pkg.title],
      ["Category", pkg.category],
      ["Sub-category", pkg.sub_category || ""],
      ["Status", pkg.status || ""],
      ["Phase", pkg.phase || ""],
      ["Estimated value", pkg.value != null ? String(pkg.value) : ""],
      ["Currency", pkg.currency || ""],
      ["Float target date", pkg.float_target_date ? pkg.float_target_date.slice(0, 10) : ""],
      ["Owner", pkg.owner_email || pkg.created_by || ""],
      ["Created at", pkg.created_at || ""],
      ["Notice reference", pkg.notice_ref || ""],
      ["Location", pkg.location || ""],
      ["Delivery country", pkg.delivery_country || ""],
      ["Duration (months)", pkg.duration_months || ""],
      ["Description", pkg.description || ""],
    ];
    const csv = "Field,Value\r\n" + rows.map(([k, v]) => `"${String(k).replace(/"/g, '""')}","${String(v).replace(/"/g, '""')}"`).join("\r\n");
    const blob = new Blob([csv], { type: "text/csv;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${pkg.package_ref || "package"}.csv`;
    document.body.appendChild(a); a.click(); a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 800);
  };

  return (
    <>
      <div
        draggable
        onDragStart={(e) => onDragStart(e, pkg)}
        role="article"
        data-testid={`pkg-card-${pkg.package_ref}`}
        className="relative border border-brand-navy/15 bg-white p-3 active:cursor-grabbing hover:border-brand-navy-soft/60 hover:shadow-sm transition-all group"
      >
        <div className="text-[9px] font-mono uppercase tracking-widest text-brand-navy-soft pr-14">{pkg.package_ref}</div>
        <div className="text-[13px] font-semibold text-brand-navy mt-1 leading-tight">{pkg.title}</div>
        <div className="text-[11px] text-brand-navy/60 mt-1">{pkg.category}</div>
        <div className="flex items-center justify-between mt-2 text-[10px] font-mono">
          <span className="text-brand-navy/70">{fmt(pkg.value, pkg.currency)}</span>
          {pkg.float_target_date && <span className="text-brand-navy/50">{pkg.float_target_date.slice(0, 10)}</span>}
        </div>
        <button
          type="button"
          onClick={(e) => { e.stopPropagation(); setOpen(true); }}
          data-testid={`pkg-card-view-${pkg.package_ref}`}
          title="View full package details"
          aria-label={`View ${pkg.package_ref}`}
          className="absolute top-2 right-2 inline-flex items-center gap-1 px-2 py-1 text-[9px] font-semibold uppercase tracking-widest border border-brand-navy/40 bg-white text-brand-navy hover:bg-brand-navy hover:text-white transition-colors">
          <svg width="10" height="10" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.4" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
            <path d="M1 12s4-8 11-8 11 8 11 8-4 8-11 8S1 12 1 12z" />
            <circle cx="12" cy="12" r="3" />
          </svg>
          View
        </button>
      </div>
      {open && (
        <div className="fixed inset-0 z-50 bg-black/50 flex items-start justify-center p-4 overflow-auto"
             onClick={() => setOpen(false)}
             data-testid={`pkg-detail-modal-${pkg.package_ref}`}>
          <div className="bg-white max-w-3xl w-full mt-10 shadow-xl border border-brand-navy/20"
               onClick={(e) => e.stopPropagation()}>
            {/* Header */}
            <div className="p-6 md:p-8 border-b border-brand-navy/10 bg-brand-pale">
              <div className="flex items-start justify-between gap-4">
                <div className="flex-1 min-w-0">
                  <div className="text-xs font-mono uppercase tracking-widest text-brand-navy-soft">Work Package · {pkg.package_ref}</div>
                  <h2 className="font-display text-2xl md:text-3xl text-brand-navy mt-1 leading-tight">{pkg.title}</h2>
                  <div className="mt-2 flex flex-wrap items-center gap-2 text-xs text-brand-navy/70">
                    <span className="px-2 py-0.5 border border-brand-navy/20 bg-white rounded-full">{pkg.category || "General"}</span>
                    {pkg.status && <span className="px-2 py-0.5 border border-brand-navy/20 bg-white rounded-full capitalize">{String(pkg.status).replace(/_/g, " ")}</span>}
                    {pkg.delivery_country && <span className="px-2 py-0.5 border border-brand-navy/20 bg-white rounded-full">{pkg.delivery_country}</span>}
                    {pkg.notice_ref && <span className="px-2 py-0.5 border border-brand-navy/20 bg-white rounded-full font-mono">{pkg.notice_ref}</span>}
                  </div>
                </div>
                <button onClick={() => setOpen(false)} data-testid={`pkg-detail-close-${pkg.package_ref}`}
                        className="text-brand-navy/60 hover:text-brand-navy text-2xl leading-none">✕</button>
              </div>
              <div className="mt-5 flex flex-wrap gap-2">
                <button type="button" onClick={handlePrint}
                        data-testid={`pkg-detail-print-${pkg.package_ref}`}
                        className="px-4 py-2 text-[11px] font-semibold uppercase tracking-widest bg-brand-navy text-white hover:bg-brand-navy-soft">
                  Print
                </button>
                <button type="button" onClick={handleDownload}
                        data-testid={`pkg-detail-download-${pkg.package_ref}`}
                        className="px-4 py-2 text-[11px] font-semibold uppercase tracking-widest border border-brand-navy text-brand-navy hover:bg-brand-navy hover:text-white">
                  Download CSV
                </button>
              </div>
            </div>

            {/* Body */}
            <div className="p-6 md:p-8 space-y-6 max-h-[70vh] overflow-y-auto">
              <section>
                <div className="pmc-label">Package details</div>
                <dl className="mt-3 grid grid-cols-1 sm:grid-cols-2 gap-x-8 gap-y-3 text-sm">
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Status</dt><dd className="text-brand-navy capitalize">{pkg.status ? String(pkg.status).replace(/_/g, " ") : "—"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Phase</dt><dd className="text-brand-navy">{pkg.phase || "—"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Category</dt><dd className="text-brand-navy">{pkg.category || "—"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Sub-category</dt><dd className="text-brand-navy">{pkg.sub_category || "—"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Estimated value</dt><dd className="text-brand-navy font-mono">{fmt(pkg.value, pkg.currency)}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Currency</dt><dd className="text-brand-navy font-mono">{pkg.currency || "—"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Float target</dt><dd className="text-brand-navy font-mono">{pkg.float_target_date ? pkg.float_target_date.slice(0, 10) : "—"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Duration</dt><dd className="text-brand-navy">{pkg.duration_months ? `${pkg.duration_months} months` : "—"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Owner</dt><dd className="text-brand-navy truncate ml-2">{pkg.owner_email || pkg.created_by || "—"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Location</dt><dd className="text-brand-navy">{pkg.location || "—"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Country</dt><dd className="text-brand-navy">{pkg.delivery_country || "—"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Notice ref</dt><dd className="text-brand-navy font-mono">{pkg.notice_ref || "Not floated yet"}</dd></div>
                  <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Created</dt><dd className="text-brand-navy font-mono text-xs">{pkg.created_at ? new Date(pkg.created_at).toLocaleString() : "—"}</dd></div>
                  {pkg.updated_at && <div className="flex justify-between border-b border-brand-navy/10 py-1.5"><dt className="text-brand-navy/60">Updated</dt><dd className="text-brand-navy font-mono text-xs">{new Date(pkg.updated_at).toLocaleString()}</dd></div>}
                </dl>
              </section>

              {pkg.description && (
                <section>
                  <div className="pmc-label">Scope / description</div>
                  <p className="mt-2 text-brand-navy/90 whitespace-pre-wrap text-sm leading-6 bg-brand-pale border border-brand-navy/10 p-4">{pkg.description}</p>
                </section>
              )}

              {Array.isArray(pkg.milestones) && pkg.milestones.length > 0 && (
                <section>
                  <div className="pmc-label">Milestones ({pkg.milestones.length})</div>
                  <ol className="mt-2 space-y-2 text-sm">
                    {pkg.milestones.map((m, i) => (
                      <li key={i} className="flex gap-3 border-l-2 border-brand-gold pl-3 py-0.5">
                        <span className="font-mono text-xs text-brand-navy/60 min-w-[90px]">
                          {m.due_date ? m.due_date.slice(0, 10) : "—"}
                        </span>
                        <span className="text-brand-navy">{m.title || m.description || "Milestone"}</span>
                      </li>
                    ))}
                  </ol>
                </section>
              )}

              {Array.isArray(pkg.deliverables) && pkg.deliverables.length > 0 && (
                <section>
                  <div className="pmc-label">Deliverables ({pkg.deliverables.length})</div>
                  <ul className="mt-2 space-y-1 text-sm list-disc pl-6 text-brand-navy/90">
                    {pkg.deliverables.map((d, i) => (
                      <li key={i}>{typeof d === "string" ? d : (d.title || d.description || "Deliverable")}</li>
                    ))}
                  </ul>
                </section>
              )}

              {Array.isArray(pkg.attached_documents) && pkg.attached_documents.length > 0 && (
                <section>
                  <div className="pmc-label">Attached documents ({pkg.attached_documents.length})</div>
                  <ul className="mt-2 space-y-2 text-sm" data-testid={`pkg-detail-docs-${pkg.package_ref}`}>
                    {pkg.attached_documents.map((d, i) => {
                      const label = d.file_name || d.filename || d.name || d.title || `Document ${i + 1}`;
                      const key = d.key || d.file_key || d.path;
                      const href = d.url || (key ? `/api/v1/uploads/files/${key}` : null);
                      const size = typeof d.size_bytes === "number"
                        ? `${(d.size_bytes / 1024).toFixed(1)} KB` : null;
                      return (
                        <li key={i} className="flex items-center justify-between gap-3 border-b border-brand-navy/10 py-2"
                            data-testid={`pkg-detail-doc-${pkg.package_ref}-${i}`}>
                          <div className="min-w-0">
                            <div className="font-medium text-brand-navy truncate">📎 {label}</div>
                            <div className="text-[11px] text-brand-navy/60">
                              {d.content_type || d.mime || "file"}
                              {size ? ` · ${size}` : ""}
                              {d.uploaded_at ? ` · uploaded ${d.uploaded_at.slice(0, 10)}` : ""}
                            </div>
                          </div>
                          <div className="shrink-0 flex gap-2">
                            {href && (
                              <a href={href} target="_blank" rel="noreferrer"
                                 data-testid={`pkg-detail-doc-view-${pkg.package_ref}-${i}`}
                                 className="px-3 py-1 text-[10px] uppercase tracking-widest border border-brand-navy/40 text-brand-navy hover:bg-brand-navy hover:text-white">
                                View
                              </a>
                            )}
                            {href && (
                              <a href={href} download={label}
                                 data-testid={`pkg-detail-doc-download-${pkg.package_ref}-${i}`}
                                 className="px-3 py-1 text-[10px] uppercase tracking-widest border border-brand-navy/40 text-brand-navy hover:bg-brand-navy hover:text-white">
                                Download
                              </a>
                            )}
                          </div>
                        </li>
                      );
                    })}
                  </ul>
                </section>
              )}

              {Array.isArray(pkg.tags) && pkg.tags.length > 0 && (
                <section>
                  <div className="pmc-label">Tags</div>
                  <div className="mt-2 flex flex-wrap gap-1.5">
                    {pkg.tags.map((t, i) => (
                      <span key={i} className="text-[11px] px-2 py-0.5 bg-brand-pale border border-brand-navy/15 text-brand-navy">{t}</span>
                    ))}
                  </div>
                </section>
              )}
            </div>
          </div>
        </div>
      )}
    </>
  );
}
